// Compile-time interface assertions.
var (
	_ datasource.DataSource              = &maintenanceWindowDataSource{}
	_ datasource.DataSourceWithConfigure = &maintenanceWindowDataSource{}
)

// NewMaintenanceWindowDataSource returns a new maintenanceWindowDataSource constructor function.
func NewMaintenanceWindowDataSource() datasource.DataSource {
	return &maintenanceWindowDataSource{}
}

// maintenanceWindowDataSource implements the data "monotaur_maintenance_window" data source.
type maintenanceWindowDataSource struct {
	client *client.Client
}

// maintenanceWindowDataSourceModel is an alias for maintenanceWindowResourceModel;
// both share the same schema shape.
type maintenanceWindowDataSourceModel = maintenanceWindowResourceModel

// Metadata sets the data source type name.
func (d *maintenanceWindowDataSource) Metadata(_ context.Context, req datasource.MetadataRequest, resp *datasource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_maintenance_window"
}

// Schema defines the Terraform schema for the data source.
func (d *maintenanceWindowDataSource) Schema(_ context.Context, _ datasource.SchemaRequest, resp *datasource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "Reads a single Monotaur maintenance window by its ID, either a one-off window or one generated by a maintenance schedule.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				MarkdownDescription: "The unique identifier of the maintenance window to look up.",
				Required:            true,
			},
			"description": schema.StringAttribute{
				MarkdownDescription: "A description of the maintenance.",
				Computed:            true,
			},
			"start_date_time": schema.StringAttribute{
				MarkdownDescription: "RFC 3339 timestamp (UTC) when the window starts.",
				Computed:            true,
			},
			"end_date_time": schema.StringAttribute{
				MarkdownDescription: "RFC 3339 timestamp (UTC) when the window ends.",
				Computed:            true,
			},
			"reason": schema.StringAttribute{
				MarkdownDescription: "Why the maintenance happens: `ScheduledMaintenance`, `EmergencyMaintenance`, `MonitoringIssue` or `ExternalIssue`.",
				Computed:            true,
			},
			"exclude_from_downtime": schema.BoolAttribute{
				MarkdownDescription: "Whether time inside the window is excluded from downtime in uptime reports.",
				Computed:            true,
			},
			"apply_to_component_status": schema.BoolAttribute{
				MarkdownDescription: "Whether the window's components show as under maintenance while it is active.",
				Computed:            true,
			},
			"squelch": schema.BoolAttribute{
				MarkdownDescription: "Whether alarm notifications for the window's components are suppressed while it is active.",
				Computed:            true,
			},
			"maintenance_schedule_id": schema.StringAttribute{
				MarkdownDescription: "The ID of the maintenance schedule the window is linked to, or null for a one-off window.",
				Computed:            true,
			},
			"create_date_time": schema.StringAttribute{
				MarkdownDescription: "The RFC 3339 timestamp when the window was created.",
				Computed:            true,
			},
			"update_date_time": schema.StringAttribute{
				MarkdownDescription: "The RFC 3339 timestamp when the window was last updated.",
				Computed:            true,
			},
		},
	}
}

// Configure extracts the *client.Client from the provider data.
func (d *maintenanceWindowDataSource) Configure(_ context.Context, req datasource.ConfigureRequest, resp *datasource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Data Source Configure Type",
			fmt.Sprintf("Expected *client.Client, got: %T. Please report this issue to the provider developers.", req.ProviderData),
		)
		return
	}

	d.client = c
}

// Read fetches the maintenance window by ID from the API.
func (d *maintenanceWindowDataSource) Read(ctx context.Context, req datasource.ReadRequest, resp *datasource.ReadResponse) {
	var config maintenanceWindowDataSourceModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	id := config.ID.ValueString()
	tflog.Debug(ctx, "monotaur_maintenance_window data source: reading maintenance window", map[string]any{"id": id})

	apiResp, err := d.client.Inner().GetMaintenanceWindow(ctx, id, maintenanceWindowReadParams())
	if err != nil {
		resp.Diagnostics.AddError("Error Reading Maintenance Window", "Could not read maintenance window "+id+": "+err.Error())
		return
	}
	defer apiResp.Body.Close()

	if err := client.CheckResponse(apiResp); err != nil {
		resp.Diagnostics.AddError("Error Reading Maintenance Window", "API returned an error: "+err.Error())
		return
	}

	data, err := client.UnmarshalDocument[api.DataInMaintenanceWindowResponse](apiResp.Body)
	if err != nil {
		resp.Diagnostics.AddError("Error Reading Maintenance Window Response", err.Error())
		return
	}

	var state maintenanceWindowDataSourceModel
	resp.Diagnostics.Append(flattenMaintenanceWindow(ctx, data, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}
